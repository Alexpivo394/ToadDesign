using System.Collections.Specialized;
using System.Runtime.CompilerServices;
using System.Windows;
using System.Windows.Controls;

namespace ToadDesign;

/// <summary>
/// DataGridCheckBoxColumn sets an explicit style on its check boxes, so implicit styles never reach them. The DataGrid
/// style turns this on: check box columns that keep the default styles (or styles made here earlier) get the
/// ToadDesign check box of the root the grid is in. Re-applied whenever the grid is loaded, so a grid moved to another
/// root follows it; consumers' own column styles are never replaced.
/// </summary>
internal static class DataGridAssist
{
    public static readonly DependencyProperty StyleColumnsProperty = DependencyProperty.RegisterAttached(
        "StyleColumns", typeof(bool), typeof(DataGridAssist), new PropertyMetadata(false, OnChanged));

    private static readonly DependencyProperty HookedProperty = DependencyProperty.RegisterAttached(
        "Hooked", typeof(bool), typeof(DataGridAssist), new PropertyMetadata(false));

    // Styles made by this class: replaceable when the grid moves to another root.
    private static readonly ConditionalWeakTable<Style, object> Made = new();

    public static bool GetStyleColumns(DependencyObject d) => (bool)d.GetValue(StyleColumnsProperty);

    public static void SetStyleColumns(DependencyObject d, bool value) => d.SetValue(StyleColumnsProperty, value);

    private static void OnChanged(DependencyObject d, DependencyPropertyChangedEventArgs e)
    {
        if (d is not DataGrid grid || !(bool)e.NewValue) return;
        if (!(bool)grid.GetValue(HookedProperty))
        {
            grid.SetValue(HookedProperty, true);
            grid.Columns.CollectionChanged += (_, args) =>
            {
                if (args.Action is NotifyCollectionChangedAction.Add or NotifyCollectionChangedAction.Replace) Apply(grid);
            };
            grid.AutoGeneratedColumns += (_, _) => Apply(grid);
            grid.Loaded += (_, _) => Apply(grid);
        }

        Apply(grid);
    }

    // Built in code: a BasedOn in XAML could not see the CheckBox style, which lives in another dictionary of the root.
    private static Style Centered(Style basedOn, bool readOnly)
    {
        var style = new Style(typeof(CheckBox), basedOn);
        style.Setters.Add(new Setter(FrameworkElement.HorizontalAlignmentProperty, HorizontalAlignment.Center));
        style.Setters.Add(new Setter(FrameworkElement.VerticalAlignmentProperty, VerticalAlignment.Center));
        if (readOnly)
        {
            style.Setters.Add(new Setter(UIElement.IsHitTestVisibleProperty, false));
            style.Setters.Add(new Setter(UIElement.FocusableProperty, false));
        }

        style.Seal();
        Made.Add(style, true);
        return style;
    }

    private static bool Replaceable(Style? current, Style defaultStyle) =>
        current == null || ReferenceEquals(current, defaultStyle) || Made.TryGetValue(current, out _);

    private static void Apply(DataGrid grid)
    {
        if (grid.TryFindResource(typeof(CheckBox)) is not Style toad) return;
        Style? element = null, editing = null;
        foreach (var column in grid.Columns)
        {
            if (column is not DataGridCheckBoxColumn check) continue;
            if (Replaceable(check.ElementStyle, DataGridCheckBoxColumn.DefaultElementStyle) && !ReferenceEquals(check.ElementStyle?.BasedOn, toad))
                check.ElementStyle = element ??= Centered(toad, readOnly: true);
            if (Replaceable(check.EditingElementStyle, DataGridCheckBoxColumn.DefaultEditingElementStyle) && !ReferenceEquals(check.EditingElementStyle?.BasedOn, toad))
                check.EditingElementStyle = editing ??= Centered(toad, readOnly: false);
        }
    }
}
