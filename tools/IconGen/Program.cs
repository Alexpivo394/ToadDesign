using System.Globalization;
using System.IO.Compression;
using System.Text;
using System.Text.Json;

// Usage: IconGen <tabler-nodes-outline.json> <src/ToadDesign/Icons>
// Input: @tabler/icons 3.49.0 (npm), file tabler-nodes-outline.json. Output: Symbol.g.cs and tabler-outline.bin
// (gzip; one line per icon, in enum order: name \t stroked path data \t filled path data).

if (args.Length != 2)
{
    Console.Error.WriteLine("usage: IconGen <tabler-nodes-outline.json> <output dir>");
    return 2;
}

using var json = JsonDocument.Parse(File.ReadAllText(args[0]));
var icons = new List<(string Name, string Member, string Stroke, string Fill)>();
var members = new HashSet<string>(StringComparer.Ordinal) { "None" };

// Symbol values are public and compiled into consumers: symbols.txt keeps the value order, append-only. Icons that a
// newer Tabler release drops keep their value with empty geometry; new icons are appended in name order.
var manifestPath = Path.Combine(args[1], "symbols.txt");
var order = File.Exists(manifestPath) ? File.ReadAllLines(manifestPath).Where(l => l.Length > 0).ToList() : new List<string>();
var source = json.RootElement.EnumerateObject().ToDictionary(p => p.Name, p => p.Value, StringComparer.Ordinal);
order.AddRange(source.Keys.Except(order, StringComparer.Ordinal).OrderBy(n => n, StringComparer.Ordinal));
foreach (var name in order)
{
    if (!source.TryGetValue(name, out var nodes))
    {
        Console.WriteLine($"kept without geometry (removed upstream): {name}");
        icons.Add((name, Member(name), "", ""));
        members.Add(Member(name));
        continue;
    }

    var icon = (Name: name, Value: nodes);
    var stroke = new StringBuilder();
    var fill = new StringBuilder();
    foreach (var node in icon.Value.EnumerateArray())
    {
        var tag = node[0].GetString();
        var attrs = node[1];
        if (tag != "path") throw new InvalidDataException($"{icon.Name}: unsupported element <{tag}>");
        var d = PathData.Canonical(attrs.GetProperty("d").GetString()!);
        var filled = attrs.TryGetProperty("fill", out var f) && f.GetString() == "currentColor";
        var stroked = !(attrs.TryGetProperty("stroke", out var s) && s.GetString() == "none");
        if (stroked) Append(stroke, d);
        if (filled) Append(fill, d);
    }

    var member = Member(icon.Name);
    if (!members.Add(member)) throw new InvalidDataException($"name collision: {icon.Name} -> {member}");
    icons.Add((icon.Name, member, stroke.ToString(), fill.ToString()));
}

var output = args[1];
File.WriteAllLines(manifestPath, order);
var code = new StringBuilder();
code.AppendLine("// <auto-generated>tools/IconGen from @tabler/icons 3.49.0 (MIT). Do not edit.</auto-generated>");
code.AppendLine("namespace ToadDesign;");
code.AppendLine();
code.AppendLine("/// <summary>Tabler outline icons (tabler.io/icons). The member name is the icon name in PascalCase.</summary>");
code.AppendLine("public enum Symbol");
code.AppendLine("{");
code.AppendLine("    /// <summary>No icon.</summary>");
code.AppendLine("    None = 0,");
for (var i = 0; i < icons.Count; i++)
{
    code.AppendLine($"    /// <summary>Tabler icon <c>{icons[i].Name}</c>.</summary>");
    code.AppendLine($"    {icons[i].Member} = {i + 1},");
}

code.AppendLine("}");
File.WriteAllText(Path.Combine(output, "Symbol.g.cs"), code.ToString(), new UTF8Encoding(false));

using (var file = File.Create(Path.Combine(output, "tabler-outline.bin")))
using (var gzip = new GZipStream(file, CompressionLevel.SmallestSize))
using (var writer = new StreamWriter(gzip, new UTF8Encoding(false)))
{
    writer.NewLine = "\n";
    foreach (var icon in icons) writer.WriteLine($"{icon.Name}\t{icon.Stroke}\t{icon.Fill}");
}

Console.WriteLine($"{icons.Count} icons -> {output}");
return 0;

static void Append(StringBuilder sb, string d)
{
    if (sb.Length > 0) sb.Append(' ');
    sb.Append(d);
}

static string Member(string name)
{
    var sb = new StringBuilder();
    foreach (var part in name.Split('-'))
        if (part.Length > 0) sb.Append(char.ToUpperInvariant(part[0])).Append(part, 1, part.Length - 1);
    var member = sb.ToString();
    return char.IsDigit(member[0]) ? "Number" + member : member;
}

/// <summary>SVG path data → canonical WPF path markup: every command letter and number separated by one space.</summary>
internal static class PathData
{
    public static string Canonical(string d)
    {
        var tokens = new List<string>();
        var i = 0;
        var command = ' ';
        var argIndex = 0;
        while (i < d.Length)
        {
            var c = d[i];
            if (char.IsWhiteSpace(c) || c == ',')
            {
                i++;
                continue;
            }

            if (char.IsLetter(c) && c != 'e' && c != 'E')
            {
                command = c;
                argIndex = 0;
                tokens.Add(c.ToString());
                i++;
                continue;
            }

            // Arc flags (4th and 5th argument of a/A) are single characters and may be written without separators.
            if ((command == 'a' || command == 'A') && (argIndex % 7 == 3 || argIndex % 7 == 4))
            {
                if (c != '0' && c != '1') throw new InvalidDataException($"bad arc flag at {i} in {d}");
                tokens.Add(c.ToString());
                argIndex++;
                i++;
                continue;
            }

            var start = i;
            if (d[i] == '+' || d[i] == '-') i++;
            var dot = false;
            while (i < d.Length && (char.IsDigit(d[i]) || (d[i] == '.' && !dot)))
            {
                if (d[i] == '.') dot = true;
                i++;
            }

            if (i < d.Length && (d[i] == 'e' || d[i] == 'E'))
            {
                i++;
                if (i < d.Length && (d[i] == '+' || d[i] == '-')) i++;
                while (i < d.Length && char.IsDigit(d[i])) i++;
            }

            if (i == start) throw new InvalidDataException($"unexpected '{c}' at {i} in {d}");
            var number = double.Parse(d.AsSpan(start, i - start), NumberStyles.Float, CultureInfo.InvariantCulture);
            tokens.Add(number.ToString("R", CultureInfo.InvariantCulture));
            argIndex++;
        }

        return string.Join(" ", tokens);
    }
}
